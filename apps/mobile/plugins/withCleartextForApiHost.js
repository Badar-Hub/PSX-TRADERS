const path = require('node:path');
const fs = require('node:fs/promises');
const { withDangerousMod } = require('expo/config-plugins');

/**
 * Lets the release build reach an API served over plain HTTP.
 *
 * Android has refused cleartext traffic by default since API 28, and this app
 * targets 34. The prebuild template only turns it on in
 * android/app/src/debug/AndroidManifest.xml, so a debug build and Expo Go both
 * work while the release APK cannot open a single connection to an http://
 * address — the one build nobody runs against a dev server, and the one that
 * gets installed on a phone. The failure reads as the API being unreachable.
 *
 * Granted per host rather than with `usesCleartextTraffic="true"`, which would
 * permit unencrypted traffic to anywhere the app talks to for the life of the
 * app. Here it is one address on a private network, and everything else stays
 * under Android's default. The host is read from `extra.apiBaseUrl` — the same
 * value the app dials — so the exception cannot drift away from the thing it
 * exists for, and an https:// API makes this plugin do nothing at all.
 *
 * Applied to the release source set rather than the main manifest, which
 * matters more than it looks: Android ignores `usesCleartextTraffic` entirely
 * once a network security config is present. Putting this in the main manifest
 * would therefore override the template's debug-only cleartext permission and
 * confine development to this one host — so `expo run:android` would stop
 * reaching the dev server from any other network, which is the opposite of
 * what the derived address in lib/config.ts exists to do.
 *
 * Delete it when staging has a certificate.
 */

const CONFIG_RESOURCE = 'network_security_config';

/** The host of a plain-HTTP API, or null if there is nothing to permit. */
function cleartextHost(config) {
  const raw = config.extra?.apiBaseUrl;
  if (typeof raw !== 'string' || raw === '') return null;

  let url;
  try {
    url = new URL(raw);
  } catch {
    throw new Error(`withCleartextForApiHost: extra.apiBaseUrl is not a URL: ${raw}`);
  }

  // https needs no exception, and localhost is already permitted by Android.
  if (url.protocol !== 'http:') return null;
  if (url.hostname === 'localhost' || url.hostname === '127.0.0.1') return null;

  return url.hostname;
}

function networkSecurityConfigXml(host) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!--
  Generated by plugins/withCleartextForApiHost.js from expo.extra.apiBaseUrl
  in app.json. Do not edit: android/ is regenerated by \`expo prebuild\`.

  Everything not listed here keeps Android's default, which refuses cleartext.
-->
<network-security-config>
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">${host}</domain>
  </domain-config>
</network-security-config>
`;
}

module.exports = function withCleartextForApiHost(config) {
  const host = cleartextHost(config);
  if (host === null) return config;

  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      const appDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src');

      // The resource itself can live in main: it has no effect unless a
      // manifest points at it, and only the release manifest does.
      const xmlDir = path.join(appDir, 'main', 'res', 'xml');
      await fs.mkdir(xmlDir, { recursive: true });
      await fs.writeFile(
        path.join(xmlDir, `${CONFIG_RESOURCE}.xml`),
        networkSecurityConfigXml(host),
        'utf8',
      );

      // A release-only manifest. The merger adds the attribute to the
      // application element from main; debug keeps the template's
      // usesCleartextTraffic and is untouched.
      const releaseDir = path.join(appDir, 'release');
      await fs.mkdir(releaseDir, { recursive: true });
      await fs.writeFile(
        path.join(releaseDir, 'AndroidManifest.xml'),
        `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withCleartextForApiHost.js. Do not edit. -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
  <application android:networkSecurityConfig="@xml/${CONFIG_RESOURCE}" />
</manifest>
`,
        'utf8',
      );

      return cfg;
    },
  ]);
};
