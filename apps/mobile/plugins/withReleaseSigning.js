const { withAppBuildGradle } = require('expo/config-plugins');

/**
 * Signs release builds with the project's own key instead of Expo's debug one.
 *
 * Expo's prebuild template points the release build type at `signingConfigs.
 * debug` and leaves a comment telling you to generate your own key. Every
 * Expo-generated APK on earth is therefore signed by the same well-known debug
 * certificate, which is fine for a build you tap to install and wrong for
 * anything else: Android identifies an app by package name *and* signing
 * certificate, so a debug-signed build cannot later be replaced by a properly
 * signed one, and the Play Store will not accept it at all.
 *
 * The key and its passwords live in credentials/keystore.properties, which is
 * gitignored. When that file is absent — a fresh clone, or CI that has no
 * business holding the signing key — storeFile stays null and the build falls
 * back to debug signing rather than failing. That keeps `expo prebuild` and a
 * plain debug build working for anyone who checks the repository out, while
 * this machine produces distributable APKs.
 *
 * android/ is gitignored and regenerated by prebuild, so this edit has to be a
 * plugin rather than a change to the generated file.
 */

const MARKER = 'psx-trader: release signing';

const SIGNING_CONFIG = `        release {
            // ${MARKER} — see plugins/withReleaseSigning.js
            // rootProject is android/, so '../' reaches the app's own folder.
            def psxKeystoreProps = rootProject.file('../credentials/keystore.properties')
            if (psxKeystoreProps.exists()) {
                def psxKeystore = new Properties()
                psxKeystoreProps.withInputStream { psxKeystore.load(it) }
                storeFile rootProject.file('../' + psxKeystore['storeFile'])
                storePassword psxKeystore['storePassword']
                keyAlias psxKeystore['keyAlias']
                keyPassword psxKeystore['keyPassword']
            }
        }
`;

/** Replaces the first occurrence of `needle` at or after `from`. */
function replaceAfter(contents, from, needle, replacement) {
  const index = contents.indexOf(needle, from);
  if (index === -1) {
    return null;
  }
  return contents.slice(0, index) + replacement + contents.slice(index + needle.length);
}

module.exports = function withReleaseSigning(config) {
  return withAppBuildGradle(config, (gradleConfig) => {
    if (gradleConfig.modResults.language !== 'groovy') {
      throw new Error(
        `withReleaseSigning expected a Groovy build.gradle, got ${gradleConfig.modResults.language}.`,
      );
    }

    if (gradleConfig.modResults.contents.includes(MARKER)) {
      return gradleConfig;
    }

    let contents = gradleConfig.modResults.contents;

    // 1. Declare the signing config alongside the template's debug one.
    const configsAnchor = '    signingConfigs {\n';
    const configsIndex = contents.indexOf(configsAnchor);
    if (configsIndex === -1) {
      throw new Error('withReleaseSigning could not find the signingConfigs block.');
    }
    contents =
      contents.slice(0, configsIndex + configsAnchor.length) +
      SIGNING_CONFIG +
      contents.slice(configsIndex + configsAnchor.length);

    // 2. Point the release build type at it. Located structurally rather than
    //    by the template's comment text, which changes between SDK versions:
    //    buildTypes -> release -> the signingConfig line inside it. The debug
    //    build type also assigns signingConfigs.debug and must be left alone,
    //    which is why this searches forward from the release block.
    const buildTypesIndex = contents.indexOf('    buildTypes {');
    if (buildTypesIndex === -1) {
      throw new Error('withReleaseSigning could not find the buildTypes block.');
    }
    const releaseIndex = contents.indexOf('release {', buildTypesIndex);
    if (releaseIndex === -1) {
      throw new Error('withReleaseSigning could not find the release build type.');
    }
    const updated = replaceAfter(
      contents,
      releaseIndex,
      'signingConfig signingConfigs.debug',
      // Falls back when the keystore properties are absent, so a clone builds.
      'signingConfig signingConfigs.release.storeFile != null ? signingConfigs.release : signingConfigs.debug',
    );
    if (updated === null) {
      throw new Error(
        'withReleaseSigning found the release build type but no signingConfig line to replace.',
      );
    }

    gradleConfig.modResults.contents = updated;
    return gradleConfig;
  });
};
