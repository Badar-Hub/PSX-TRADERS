<#
    Builds an installable release APK locally, without EAS and without an
    Android Studio install.

    Everything this needs lives under %USERPROFILE%\dev-tools, installed from
    zips so no administrator rights are involved:

        jdk-17.0.20.1+1   Gradle 8.10 refuses JDK 25, which is what Android
                          Studio bundles, so the toolchain gets its own JDK.
        android-sdk       cmdline-tools, platform-tools, platforms\android-35,
                          build-tools\35.0.0.

    Redirecting TEMP is the load-bearing line. Gradle's launcher opens an NIO
    Selector to reach its daemon, a Selector on Windows needs a self-pipe, and a
    JDK 17 self-pipe is an AF_UNIX socket created in java.io.tmpdir. On this
    machine TEMP arrives as C:\Users\BADARA~1\... - an 8.3 short-name alias -
    and AF_UNIX connect() rejects it with "Invalid argument", which surfaces as
    the entirely misleading "Unable to establish loopback connection".

    Giving the build a TEMP with a real name fixes it for every JVM the build
    starts. The two narrower fixes both fail: -D in org.gradle.jvmargs is
    stripped out of the args Gradle hands its forked daemon, and setting
    JAVA_TOOL_OPTIONS makes every child JVM print "Picked up
    JAVA_TOOL_OPTIONS:" on stderr - which AGP reads as output from the prefab
    CLI and reports as "[CXX1210] No compatible library found".

    android\ is gitignored and regenerated by `expo prebuild`, so this script,
    not anything inside it, is where the knowledge lives.

    The other thing that had to be solved to build here is in
    plugins/withShortNativeBuildPath.js: Windows long paths are disabled on
    this machine (LongPathsEnabled = 0, and changing it needs administrator
    rights) and CMake will not place an object file more than 250 characters
    deep, which expo-modules-core's C++ sources otherwise exceed by a wide
    margin. That plugin moves each module's .cxx directory to C:\b\<module>.
    The app keeps the new architecture; only the build directory moved.
#>

$ErrorActionPreference = 'Stop'

$tools   = Join-Path $env:USERPROFILE 'dev-tools'
$mobile  = Split-Path $PSScriptRoot -Parent
$android = Join-Path $mobile 'android'

$env:JAVA_HOME        = Join-Path $tools 'jdk-17.0.20.1+1'
$env:ANDROID_HOME     = Join-Path $tools 'android-sdk'
$env:ANDROID_SDK_ROOT = $env:ANDROID_HOME
$env:Path             = (Join-Path $env:JAVA_HOME 'bin') + ';' + $env:Path

$tmp = Join-Path $tools 'tmp'
if (-not (Test-Path $tmp)) { New-Item -ItemType Directory $tmp | Out-Null }
$env:TMP  = $tmp
$env:TEMP = $tmp

# EXPO_NO_METRO_WORKSPACE_ROOT is the second load-bearing line. React Native's
# Gradle plugin passes --entry-file as a path relative to the app
# (apps/mobile -> "index.js"), while Expo's export:embed resolves it against
# Metro's "server root", which in a workspace is the monorepo root. The two
# agree only outside a monorepo; here the bundle step fails with "Unable to
# resolve module ./index.js". This tells Expo to keep the server root at the
# app, so both ends mean the same directory. It is set only for this build, so
# `expo start` keeps the workspace-wide server root it wants in development.
$env:EXPO_NO_METRO_WORKSPACE_ROOT = '1'

if (-not (Test-Path $env:JAVA_HOME)) { throw "No JDK at $env:JAVA_HOME" }
if (-not (Test-Path $env:ANDROID_HOME)) { throw "No Android SDK at $env:ANDROID_HOME" }

# The native project is generated, not committed. Recreate it when absent.
if (-not (Test-Path (Join-Path $android 'gradlew.bat'))) {
    Write-Host 'No android/ directory - running expo prebuild.'
    Push-Location $mobile
    try { npx expo prebuild --platform android } finally { Pop-Location }
}

# local.properties is also generated; Gradle needs it to find the SDK. Forward
# slashes, because a Java properties file reads a backslash as an escape.
$sdkPath = $env:ANDROID_HOME.Replace('\', '/')
Set-Content -Path (Join-Path $android 'local.properties') -Value "sdk.dir=$sdkPath" -Encoding utf8

Push-Location $android
try {
    & .\gradlew.bat assembleRelease
    if ($LASTEXITCODE -ne 0) { throw "Gradle failed with exit code $LASTEXITCODE" }
} finally {
    Pop-Location
}

$apk = Join-Path $android 'app\build\outputs\apk\release\app-release.apk'
if (-not (Test-Path $apk)) { throw "Gradle reported success but $apk is missing" }

$size = [Math]::Round((Get-Item $apk).Length / 1MB, 1)
Write-Host ''
Write-Host "APK: $apk ($size MB)"

# Say which key signed it, because the two cases install very differently and
# the build itself falls back silently when the keystore is not present.
$keystoreProps = Join-Path $mobile 'credentials\keystore.properties'
if (Test-Path $keystoreProps) {
    $alias = (Select-String -Path $keystoreProps -Pattern '^keyAlias=(.+)$').Matches.Groups[1].Value
    Write-Host "Signed with the project's release key (alias '$alias')."
    Write-Host 'Back up credentials\ somewhere safe: an app signed with a'
    Write-Host 'different key cannot replace one already installed.'
} else {
    Write-Host 'No credentials\keystore.properties - signed with Expo''s debug key.'
    Write-Host 'Installable by hand, but not upgradable and not publishable.'
}
